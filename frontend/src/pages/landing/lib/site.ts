// 측정소는 25개 구 가운데 고르게 10곳만 찍는다(25곳 모두 찍으면 지도가 점으로 덮인다). 위치는 대략(구청 둘레)이고 값은 넣지 않았다

export type Pin = {
  at: [number, number];
  /** 보도자료 점(흰 바탕 + 남색 테두리) */
  doc?: boolean;
  /** 말풍선: 굵은 종류 + 설명 */
  kind?: string;
  text?: string;
};

/** [이름, 경도, 위도, 나타나는 확대, 사라지는 확대, 종류] — 지명은 확대에 따라 시 → 둘레 시 · 군 → 구로 바뀐다 */
export type Place = [string, number, number, number, number, ("city" | "gu")?];

export type Site = {
  target: { lon: number; lat: number };
  center: [number, number];
  /** 구운 지도 파일 이름: liberty-<tag><확대>.webp */
  tag: string;
  final: { center: [number, number]; zoom: number; pitch: number; bearing: number };
  pins: Pin[];
  places: Place[];
};

